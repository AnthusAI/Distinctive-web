def decision_at_a_glance(ruling: Ruling) -> str:
    rows = []
    if ruling.caption:
        rows.append(glance_row("Caption", f"<strong>{escaped(ruling.caption)}</strong>"))
    if ruling.proceeding or ruling.proceeding_number:
        rows.append(glance_row("Proceeding", escaped(" · ".join(part for part in [ruling.proceeding, ruling.proceeding_number] if part))))
    if ruling.date:
        rows.append(glance_row("Decided", escaped(format_long_date(ruling.date))))
    if ruling.panel:
        rows.append(glance_row("Panel", escaped(ruling.panel)))
    if ruling.issue_label:
        rows.append(glance_row("Issue", escaped(ruling.issue_label)))
    if ruling.outcome:
        rows.append(glance_row("Outcome", outcome_badge(ruling.outcome)))
    rows.append(glance_row("Status", escaped(ruling.status_label)))
    opinion = (
        f'<a class="ds-block-button" href="{escaped(ruling.opinion_url)}" rel="noopener">Read the opinion on TTABVUE ↗</a>'
        if ruling.opinion_url
        else ""
    )
    return (
        '<div class="ds-glance">'
        '<h2 class="ds-rule-heading" id="glance-heading">Decision at a glance</h2>'
        f'<dl>{"".join(rows)}</dl>{opinion}</div>'
    )


def filed_under_chips(entry: Commentary | Ruling) -> str:
    topics = list(dict.fromkeys([*( [entry.issue] if isinstance(entry, Ruling) and entry.issue else []), *entry.tags]))
    if not topics:
        return ""
    chips = "".join(f'<a class="ds-chip" href="/rulings/?issue={escaped(topic)}">{escaped(topic)}</a>' for topic in topics)
    return f'<div class="ds-filed-under ds-filed-under--article"><span class="ds-filed-under__label">Filed under</span>{chips}</div>'


def related_card(entry: Commentary | Ruling) -> str:
    if isinstance(entry, Ruling):
        eyebrow = f"{entry.caption} · {entry.status_label}"
    else:
        eyebrow = entry.kicker or "Commentary"
    return (
        f'<a class="ds-related-card" href="{entry.href}">'
        f'<span class="ds-mono-meta ds-mono-meta--small">{escaped(eyebrow)}</span>'
        f'<span class="ds-related-card__headline">{escaped(entry.title)}</span></a>'
    )


def insert_before_second_section(article_html: str, insertion: str) -> str:
    heading_marker = "<h2"
    first = article_html.find(heading_marker)
    second = article_html.find(heading_marker, first + 1) if first >= 0 else -1
    if second < 0:
        return article_html + insertion
    return article_html[:second] + insertion + article_html[second:]


def story_page_body(settings: SiteSettings, content: SiteContent, entry: Commentary | Ruling, article_html: str) -> str:
    is_ruling = isinstance(entry, Ruling)
    if is_ruling:
        breadcrumb = (
            '<a href="/rulings/">TTAB Rulings</a><span aria-hidden="true">/</span>'
            f'<span class="ds-breadcrumb__current">{escaped(entry.issue or entry.issue_label)}</span>'
            f'<span aria-hidden="true">/</span><span>{escaped(entry.status_label)}</span>'
        )
        figure = marks_figure(entry, "article")
        side_top = decision_at_a_glance(entry)
        placement = "ruling"
    else:
        breadcrumb = (
            '<a href="/commentary/">Commentary</a>'
            + (f'<span aria-hidden="true">/</span><span class="ds-breadcrumb__current">{escaped(entry.kicker)}</span>' if entry.kicker else "")
        )
        figure = ""
        side_top = ""
        placement = "commentary"
    byline = "".join(
        f'<span class="{"ds-byline__author" if index == 0 and entry.author else ""}">{escaped(part)}</span>'
        for index, part in enumerate(
            [part for part in [f"By {entry.author}" if entry.author else "", format_long_date(entry.date), f"{entry.read_minutes} min read" if entry.read_minutes else ""] if part]
        )
    )
    dek = f'<p class="ds-story-header__dek">{escaped(entry.dek)}</p>' if entry.dek else ""
    body_with_signup = insert_before_second_section(article_html, inline_article_signup(settings))
    related = content.related_entries(entry)
    related_section = ""
    if related:
        topic = entry.issue if is_ruling and entry.issue else "this topic"
        related_section = (
            '<section class="ds-white-band ds-white-band--related" aria-labelledby="more-heading"><div class="ds-container ds-stack">'
            f'<h2 class="ds-section-heading__title" id="more-heading">More on {escaped(topic)}</h2>'
            f'<div class="ds-related-grid">{"".join(related_card(other) for other in related)}</div></div></section>'
        )
    end_signup = dark_signup_panel(
        settings,
        "story-end-email",
        "Don’t miss the next precedential decision.",
        f"{settings.newsletter['name']}: notable rulings analyzed, every decision summarized. Free, every Friday.",
        show_recent_issue_link=True,
    )
    return (
        '<main><article class="ds-story">'
        '<div class="ds-container ds-story-header">'
        f'<nav class="ds-breadcrumb" aria-label="Breadcrumb">{breadcrumb}</nav>'
        f'<h1 class="ds-story-header__headline">{escaped(entry.title)}</h1>'
        f"{dek}"
        f'<div class="ds-byline">{byline}</div>'
        f"{figure}"
        "</div>"
        '<div class="ds-container ds-story-layout">'
        '<aside class="ds-story-layout__side" aria-label="About this story">'
        f"{side_top}"
        f'<div class="ds-story-layout__sponsor">{sponsor_sidebar(settings, placement + "-sidebar")}</div>'
        "</aside>"
        '<div class="ds-story-layout__body">'
        f'<div class="ds-prose">{body_with_signup}</div>'
        f'<div class="ds-story-layout__banner">{sponsor_banner(settings, placement + "-banner")}</div>'
        f"{filed_under_chips(entry)}"
        "</div></div></article>"
        f'<div class="ds-container ds-spaced-unit">{end_signup}</div>'
        f"{related_section}"
        "</main>"
    )



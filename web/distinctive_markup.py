def commentary_card(entry: Commentary, heading_level: str = "h3") -> str:
    meta = " · ".join(part for part in [entry.author, f"{entry.read_minutes} min read" if entry.read_minutes else ""] if part)
    dek = f'<p class="ds-commentary-card__dek">{escaped(entry.dek)}</p>' if entry.dek else ""
    kicker = f'<span class="ds-kicker ds-kicker--accent">{escaped(entry.kicker)}</span>' if entry.kicker else ""
    meta_html = f'<span class="ds-commentary-card__meta">{escaped(meta)}</span>' if meta else ""
    return (
        '<article class="ds-commentary-card">'
        f"{kicker}"
        f'<{heading_level} class="ds-commentary-card__headline"><a href="{entry.href}">{escaped(entry.title)}</a></{heading_level}>'
        f"{dek}{meta_html}"
        "</article>"
    )



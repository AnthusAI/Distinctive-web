def sponsor_phone_link(settings: SiteSettings, class_name: str) -> str:
    sponsor = settings.sponsor
    if not sponsor.get("phoneLabel"):
        return ""
    href = sponsor.get("phoneUrl") or sponsor_consultation_href(settings)

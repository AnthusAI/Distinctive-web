def escaped(value) -> str:
    return html.escape(str(value or ""), quote=True)


@dataclass(frozen=True)
class SiteSettings:
    configuration: dict
    site_url: str | None

    @property
    def publication(self) -> dict:
        return self.configuration["publication"]

    @property
    def newsletter(self) -> dict:
        return self.configuration["newsletter"]

    @property
    def sponsor(self) -> dict:
        return self.configuration["sponsor"]

    @property
    def shows_sponsor_units(self) -> bool:
        return not self.sponsor.get("isPlaceholder") or bool(self.sponsor.get("showWhilePlaceholder"))

    def sponsor_pitch(self, placement: str) -> str:
        return self.configuration.get("sponsorPitches", {}).get(placement, "")

    def absolute_url(self, path: str) -> str | None:
        return f"{self.site_url.rstrip('/')}{path}" if self.site_url else None


def wordmark(class_name: str) -> str:
    return (
        f'<span class="{class_name}"><span class="ds-wordmark__distinctive">Distinctive</span> '
        '<span class="ds-wordmark__mark">Mark<span class="ds-trademark-sign">™</span></span></span>'
    )


def wordmark_with_tagline(settings: SiteSettings, variant: str) -> str:
    return (
        f'<span class="ds-lockup ds-lockup--{variant}">{wordmark("ds-wordmark")}'
        f'<span class="ds-tagline">{escaped(settings.publication["tagline"])}</span></span>'
    )


SECTION_NAVIGATION = (
    ("TTAB Rulings", "/rulings/", "rulings"),
    ("Commentary", "/commentary/", "commentary"),
    ("The Wire", "/wire/", "wire"),
    ("Before You File", "/guides/", "guides"),
)


def section_link(label: str, href: str, is_current: bool, class_name: str) -> str:
    current = ' aria-current="page"' if is_current else ""
    return f'<a class="{class_name}" href="{href}"{current}>{escaped(label)}</a>'


def compact_site_header(settings: SiteSettings, current_section: str | None, shows_sponsor_bar: bool = False) -> str:
    links = "".join(
        section_link(label, href, key == current_section, "ds-compact-header__link") for label, href, key in SECTION_NAVIGATION
    )
    return (
        '<header class="ds-compact-header"><div class="ds-container ds-compact-header__row">'
        f'<a class="ds-compact-header__home" href="/">{wordmark_with_tagline(settings, "inline")}</a>'
        f'<nav class="ds-compact-header__nav" aria-label="Sections">{links}'
        '<a class="ds-pill-button ds-pill-button--accent" href="/subscribe/">Subscribe</a></nav>'
        f"</div>{sponsor_bar(settings) if shows_sponsor_bar else ''}</header>"
    )


def home_site_header(settings: SiteSettings, content: SiteContent) -> str:
    standing_slugs = content.standing_page_slugs
    extra_links = [
        ("USPTO", "/wire/?source=USPTO"),
        ("Courts", "/wire/?source=Courts"),
    ]
    if "about" in standing_slugs:
        extra_links.append(("About", "/about/"))
    section_links = "".join(section_link(label, href, False, "ds-section-nav__link") for label, href, _key in SECTION_NAVIGATION)
    section_links += "".join(section_link(label, href, False, "ds-section-nav__link") for label, href in extra_links)
    present_issues = {ruling.issue for ruling in content.rulings}
    chip_labels = settings.configuration.get("issueChipLabels", {})
    issue_chips = "".join(
        f'<a class="ds-chip" href="/rulings/?issue={escaped(issue)}">{escaped(chip_labels.get(issue, issue))}</a>'
        for issue in settings.configuration.get("issueFilters", [])
        if issue in present_issues
    )
    filed_under = (
        f'<div class="ds-filed-under"><span class="ds-filed-under__label">Filed under</span>{issue_chips}</div>' if issue_chips else ""
    )
    return (
        '<div class="ds-utility-bar"><div class="ds-container ds-utility-bar__row">'
        '<span data-ds-today=""></span>'
        '<div class="ds-utility-bar__actions">'
        '<a class="ds-pill-button ds-pill-button--accent ds-pill-button--small" href="/subscribe/">Subscribe</a>'
        '<a class="ds-utility-bar__link" href="/feed.xml">RSS</a>'
        "</div></div></div>"
        '<header class="ds-container ds-home-masthead">'
        '<div class="ds-home-masthead__row">'
        f'<a class="ds-home-masthead__lockup" href="/">{wordmark("ds-wordmark ds-wordmark--display")}'
        f'<span class="ds-tagline ds-tagline--display">{escaped(settings.publication["tagline"])}</span></a>'
        f'<p class="ds-home-masthead__description">{escaped(settings.publication["description"])}</p>'
        "</div>"
        f'<nav class="ds-section-nav" aria-label="Sections">{section_links}</nav>'
        f"{filed_under}"
        "</header>"
    )


def site_footer(settings: SiteSettings, content: SiteContent, notice: str | None = None, show_links: bool = False) -> str:
    links_html = ""
    if show_links:
        footer_links = [(page.title, page.href) for page in content.standing_pages]
        footer_links.append(("Contact", "/contact/"))
        footer_links.append(("RSS", "/feed.xml"))
        links_html = '<nav class="ds-footer__links" aria-label="Footer">' + "".join(
            f'<a href="{escaped(href)}">{escaped(label)}</a>' for label, href in footer_links
        ) + "</nav>"
    publication = settings.publication
    return (
        '<footer class="ds-footer"><div class="ds-container ds-footer__layout">'
        f'<div class="ds-footer__top">{wordmark_with_tagline(settings, "stacked")}{links_html}</div>'
        f'<p class="ds-footer__notice">{escaped(notice or publication["legalNotice"])}</p>'
        f'<span class="ds-footer__copyright">© {escaped(publication["copyrightYear"])} {escaped(publication.get("publisher") or publication["name"])}</span>'
        "</div></footer>"
    )



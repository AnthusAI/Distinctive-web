def notable_ruling_hero(ruling: Ruling) -> str:
    reasons = "".join(f"<li>{escaped(reason)}</li>" for reason in ruling.reasons_notable)
    reasons_panel = (
        f'<div class="ds-notable-hero__reasons"><span class="ds-notable-hero__reasons-label">Why it’s notable</span><ul>{reasons}</ul></div>'
        if reasons
        else ""
    )
    meta = " · ".join(part for part in [ruling.issue, ruling.status_label, format_short_date_with_year(ruling.date)] if part)
    case_line = " · ".join(part for part in [ruling.caption, ruling.proceeding_number, ruling.outcome] if part)
    byline = " · ".join(byline_parts(ruling))
    dek = ruling.dek or ruling.one_line_summary
    return (
        '<article class="ds-notable-hero">'
        '<div class="ds-notable-hero__main">'
        f'<div class="ds-notable-hero__meta">{notability_meter(ruling.notability, "large")}'
        '<span class="ds-notable-hero__rating">Highly notable</span>'
        f'<span class="ds-mono-meta">{escaped(meta)}</span></div>'
        f'<h3 class="ds-notable-hero__headline"><a href="{ruling.href}">{escaped(ruling.headline)}</a></h3>'
        f'<span class="ds-case-line">{escaped(case_line)}</span>'
        f'<p class="ds-notable-hero__dek">{escaped(dek)}</p>'
        '<div class="ds-notable-hero__actions">'
        f'<a class="ds-pill-button ds-pill-button--ink" href="{ruling.href}">Read the analysis</a>'
        f'<span class="ds-notable-hero__byline">{escaped(byline)}</span></div>'
        "</div>"
        f"{reasons_panel}"
        "</article>"
    )


def notable_ruling_card(ruling: Ruling) -> str:
    meta = " · ".join(part for part in [ruling.issue, ruling.status_label if ruling.is_precedential else "", format_short_date(ruling.date)] if part)
    case_line = " · ".join(part for part in [ruling.caption, ruling.outcome] if part)
    byline = " · ".join(byline_parts(ruling))
    dek = ruling.dek or ruling.one_line_summary
    return (
        '<article class="ds-notable-card">'
        f'<div class="ds-notable-card__meta">{notability_meter(ruling.notability, "medium")}<span class="ds-mono-meta ds-mono-meta--small">{escaped(meta)}</span></div>'
        f'<h3 class="ds-notable-card__headline"><a href="{ruling.href}">{escaped(ruling.headline)}</a></h3>'
        f'<span class="ds-case-line ds-case-line--small">{escaped(case_line)}</span>'
        f'<p class="ds-notable-card__dek">{escaped(dek)}</p>'
        f'<span class="ds-notable-card__byline">{escaped(byline)}</span>'
        "</article>"
    )


def filter_buttons(group_label: str, filter_name: str, labels: list[str], label_column: str, accent_selected: bool = False) -> str:
    buttons = "".join(
        f'<button class="ds-filter-button{" ds-filter-button--accent" if accent_selected else ""}" type="button" '
        f'data-ds-filter="{filter_name}" data-ds-filter-value="{escaped(value)}" aria-pressed="{"true" if index == 0 else "false"}">{escaped(label)}</button>'
        for index, (value, label) in enumerate(labels)
    )
    return (
        f'<div class="ds-filter-group" role="group" aria-label="{escaped(group_label)}">'
        f'{f"<span class=ds-filter-group__label>{escaped(label_column)}</span>" if label_column else ""}{buttons}</div>'
    )


def ruling_row(ruling: Ruling) -> str:
    link_label = "Read the analysis →" if ruling.is_notable else "Read the summary →"
    detail = " · ".join(part for part in [ruling.proceeding_number and f"{ruling.proceeding} · {ruling.proceeding_number}" or ruling.proceeding, ruling.status_label, ruling.issue_label] if part)
    month_anchor = f"{ruling.date:%Y-%m}" if ruling.date else ""
    return (
        f'<li class="ds-ruling-row" data-ds-row="ruling" data-ds-issue="{escaped(ruling.issue)}" '
        f'data-ds-notable="{"true" if ruling.is_notable else "false"}" data-ds-precedential="{"true" if ruling.is_precedential else "false"}" '
        f'data-ds-month="{month_anchor}">'
        '<div class="ds-ruling-row__date">'
        f'<time datetime="{ruling.date.isoformat() if ruling.date else ""}">{escaped(format_short_date_with_year(ruling.date))}</time>'
        f'{notability_meter(ruling.notability, "small")}</div>'
        '<div class="ds-ruling-row__body">'
        f'<h3 class="ds-ruling-row__caption"><a href="{ruling.href}">{escaped(ruling.caption or ruling.title)}</a></h3>'
        f'<span class="ds-mono-meta ds-mono-meta--case">{escaped(detail)}</span>'
        f'<p class="ds-ruling-row__summary">{escaped(ruling.one_line_summary)}</p></div>'
        '<div class="ds-ruling-row__outcome">'
        f"{outcome_badge(ruling.outcome)}"
        f'<a class="ds-mono-link ds-mono-link--underlined" href="{ruling.href}">{link_label}</a></div>'
        "</li>"
    )


SPONSOR_ROW_POSITIONS = (3, 9)


def ruling_rows_with_sponsors(settings: SiteSettings, rulings: list[Ruling]) -> str:
    rows = []
    for index, ruling in enumerate(rulings):
        rows.append(ruling_row(ruling))
        if index in SPONSOR_ROW_POSITIONS and settings.shows_sponsor_units:
            rows.append(f'<li class="ds-feed-sponsor-row" data-ds-row="sponsor">{sponsor_feed_row(settings, "rulings-feed")}</li>')
    return "".join(rows)



def notability_meter(notability: int, size: str) -> str:
    segments = "".join(
        f'<span class="ds-meter__segment{" ds-meter__segment--filled" if position <= notability else ""}"></span>'
        for position in range(1, MAXIMUM_NOTABILITY + 1)
    )
    return f'<div class="ds-meter ds-meter--{size}" role="img" aria-label="Notability {notability} of {MAXIMUM_NOTABILITY}">{segments}</div>'


def outcome_badge(outcome: str) -> str:
    return f'<span class="ds-outcome-badge">{escaped(outcome)}</span>' if outcome else ""


def byline_parts(entry: Commentary | Ruling) -> list[str]:
    parts = []
    if entry.author:
        parts.append(f"By {entry.author}")
    if entry.read_minutes:
        parts.append(f"{entry.read_minutes} min read")
    return parts


def marks_figure(ruling: Ruling, size: str) -> str:
    if not ruling.marks_at_issue:
        return ""
    panels = "".join(
        '<div class="ds-marks-figure__panel">'
        f'<span class="ds-marks-figure__label">{escaped(mark.label)}{" · " + escaped(mark.number) if mark.number else ""}</span>'
        f'<span class="ds-marks-figure__mark">{escaped(mark.mark)}</span>'
        f'<span class="ds-marks-figure__goods">{escaped(mark.goods)}</span>'
        "</div>"
        for mark in ruling.marks_at_issue
    )
    year = f" (TTAB {ruling.date.year})" if ruling.date else ""
    if size == "card":
        caption = (
            '<figcaption class="ds-marks-figure__footer">'
            f"<span>{escaped(ruling.caption)}{year}</span>"
            f'<span class="ds-marks-figure__outcome">{escaped(ruling.outcome)}</span></figcaption>'
        )
        return f'<figure class="ds-marks-figure ds-marks-figure--card"><div class="ds-marks-figure__grid">{panels}</div>{caption}</figure>'
    return (
        '<figure class="ds-marks-figure ds-marks-figure--article">'
        '<figcaption class="ds-marks-figure__header">The marks at issue</figcaption>'
        f'<div class="ds-marks-figure__grid">{panels}</div></figure>'
    )


def lead_story(settings: SiteSettings, entry: Commentary | Ruling) -> str:
    if isinstance(entry, Ruling):
        kicker_parts = ["TTAB", entry.status_label if entry.is_precedential else "", entry.issue]
        figure = marks_figure(entry, "card")
    else:
        kicker_parts = [entry.kicker or "Commentary"]
        figure = ""
    kicker = " · ".join(part for part in kicker_parts if part)
    meta = [*byline_parts(entry)]
    if entry.date:
        meta.insert(1 if entry.author else 0, format_long_date(entry.date))
    meta_html = "".join(f"<span>{escaped(part)}</span>" for part in meta)
    dek = f'<p class="ds-lead-story__dek">{escaped(entry.dek)}</p>' if entry.dek else ""
    return (
        '<article class="ds-lead-story">'
        f'<div class="ds-kicker ds-kicker--accent">{escaped(kicker)}</div>'
        f'<h1 class="ds-lead-story__headline"><a href="{entry.href}">{escaped(entry.title)}</a></h1>'
        f"{dek}"
        f'<div class="ds-meta-line">{meta_html}</div>'
        f"{figure}"
        "</article>"
    )


